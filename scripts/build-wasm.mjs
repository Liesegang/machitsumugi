import { spawnSync } from 'node:child_process';
import { mkdir, copyFile, stat, readFile, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const root = fileURLToPath(new URL('../', import.meta.url));
const manifest = path.join(root, 'wasm/terrain-kernel/Cargo.toml');
const sourceFiles = ['Cargo.toml', 'Cargo.lock', 'src/lib.rs'];
const sourceHash = async () => {
  const hash = createHash('sha256');
  for (const name of sourceFiles) { hash.update(name); hash.update((await readFile(path.join(root, 'wasm/terrain-kernel', name), 'utf8')).replace(/\r\n/g, '\n')); }
  return hash.digest('hex');
};
if (process.argv.includes('--check')) {
  const expected = JSON.parse(await readFile(path.join(root, 'public/compute/terrain-manifest.json'), 'utf8'));
  const binary = await readFile(path.join(root, 'public/compute/terrain.wasm'));
  const version = await readFile(path.join(root, 'src/compute/terrain-kernel-version.ts'), 'utf8');
  if (expected.sourceSha256 !== await sourceHash() || expected.binarySha256 !== createHash('sha256').update(binary).digest('hex') || !version.includes(expected.binarySha256) || !version.includes(expected.sourceSha256)) throw new Error('Terrain WASM is stale; run npm run build:wasm');
  console.log('Terrain WASM source/binary/version verified');
  process.exit(0);
}
const built = spawnSync('cargo', ['build', '--release', '--target', 'wasm32-unknown-unknown', '--manifest-path', manifest], { stdio: 'inherit', cwd: root, env: { ...process.env, RUSTFLAGS: `${process.env.RUSTFLAGS ?? ''} -C link-arg=--max-memory=268435456`.trim() } });
if (built.error) throw built.error;
if (built.status !== 0) process.exit(built.status ?? 1);
const directory = path.join(root, 'public/compute');
await mkdir(directory, { recursive: true });
const output = path.join(directory, 'terrain.wasm');
await copyFile(path.join(root, 'wasm/terrain-kernel/target/wasm32-unknown-unknown/release/terrain_kernel.wasm'), output);
const sourceSha256 = await sourceHash(), binarySha256 = createHash('sha256').update(await readFile(output)).digest('hex');
await writeFile(path.join(directory, 'terrain-manifest.json'), JSON.stringify({ abi: 1, sourceSha256, binarySha256 }, null, 2) + '\n');
await mkdir(path.join(root, 'src/compute'), { recursive: true });
await writeFile(path.join(root, 'src/compute/terrain-kernel-version.ts'), `// Generated by scripts/build-wasm.mjs; do not edit.\nexport const TERRAIN_WASM_SHA256 = '${binarySha256}'\nexport const TERRAIN_SOURCE_SHA256 = '${sourceSha256}'\n`);
console.log(`Terrain WASM: ${path.relative(root, output)} (${(await stat(output)).size} bytes)`);
